"""Root-cause checks B and D (docs/notes/mechanism-root-cause.md, D-028, DR-019). Exploratory (D-015). Nothing here is a method.

Registered tags (exploratory/oracle.py TAGS):
  mb1  check B: oracle directions next to backprop (F' exact gradient, P pinv, Q damped logit, Pr = P bounded), relu and tanh
       phase 1 screen rho (seeds 700-702), phase 2 test (seeds 710-719), phase 3 lr x 0.5 / 2 on P and Q
  md1  check D: replacement (backprop cut at h): R1 learned G (tuned), R1w with backprop first, R2 oracle P, R4 frozen random G

Order (full commands in the note):
  python scripts/run_sweep.py --tag t13 --arms base_tanh ...      # tuned tanh baseline        (then analyze.py select --write-configs)
  python scripts/run_sweep.py --tag t4  --arms meet_replace ...   # tuned learned replacement  (then analyze.py select --write-configs)
  python scripts/run_root_cause.py --tag mb1 --phase 1 --workers 4 [--write-configs first, commit the configs]
  python scripts/run_root_cause.py --tag mb1 --phase 1 --analyze-only --write-chosen
  python scripts/run_root_cause.py --tag mb1 --phase 2 ... ; --phase 3 ... ; --tag md1 ...

Options: --dry-run (what would run), --limit N, --analyze-only, --write-configs (writes configs/oracle/<tag>_<group>.yaml from
the derivation in exploratory/oracle.py; the files are checked against it before every run), --settings relu tanh (default both).
Raw logs go to results/raw/oracle/<tag>/ (finished runs are skipped, never overwritten); tables to results/processed/oracle_<tag>_p<phase>.csv.
Torch threads: one per worker by default (E-011). --smoke needs --max-steps, --seeds and an --out-dir other than the default.
"""
import argparse
import csv
import multiprocessing as mp
import pathlib
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed

import numpy as np
import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))  # run from anywhere

from exploratory import oracle
from src.final import FinalJob, existing_run, run_final_job


def _init_worker(threads):
    import torch
    torch.set_num_threads(threads)


def specs_of(tag, phase, settings, seeds):
    specs = oracle.group_specs(tag, phase, settings)
    if seeds is not None:
        specs = [{**s, "seeds": tuple(seeds)} for s in specs]
    return specs


def ensure_configs(tag, specs, write=False):
    """The config files must equal the derivation in exploratory/oracle.py (no hand edits). Missing files are written only
    with write=True."""
    for s in specs:
        path, want = oracle.config_path(tag, s["name"]), oracle.build_config(s, tag)
        if not path.exists():
            if not write:
                sys.exit(f"{path} is missing; run with --write-configs, commit it, and then run")
            path.parent.mkdir(parents=True, exist_ok=True)
            header = (f"# Check {oracle.tag_spec(tag)['check']}, tag {tag}, group {s['name']} (kind {s['kind']}). Generated by "
                      f"scripts/run_root_cause.py from exploratory/oracle.py; do not edit.\n")
            path.write_text(header + yaml.safe_dump(want, sort_keys=False))
        elif yaml.safe_load(open(path)) != want:
            sys.exit(f"{path} differs from its derivation in exploratory/oracle.py (hand edit, or the tuned config it is derived "
                     f"from changed since it was written?)")


def make_jobs(tag, specs, out_dir):
    """Seed-major order, so a stopped run leaves every group with the same seeds done."""
    by_seed = sorted({(seed, i) for i, s in enumerate(specs) for seed in s["seeds"]})
    return [FinalJob(specs[i]["name"], seed, str(oracle.config_path(tag, specs[i]["name"])), str(out_dir)) for seed, i in by_seed]


def write_csv(specs, scores, path, n_boot=10000):
    rows = []
    for s in specs:
        g = scores[s["name"]]
        r = dict(group=s["name"], kind=s["kind"], setting=s["setting"] or "", rho=s["rho"] if s["rho"] is not None else "",
                 lr_mult=s["lr_mult"], n=len(g["seeds"]), mean_final_acc=float(np.mean(g["final"])), h_var=g["h_var"], align=g["align"])
        for t in oracle.TARGETS:
            r[f"mean_steps_{t}"] = float(np.mean(g["steps"][t]))
            r[f"n_reached_{t}"] = int(sum(g["reached"][t]))
        if s["ref"] is not None:
            ch = oracle.change(scores[s["ref"]], g, n_boot=n_boot)
            for t in oracle.TARGETS:
                r[f"change_pct_{t}"], r[f"lo_{t}"], r[f"hi_{t}"] = ch[t]
        rows.append(r)
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {path}")


def analyze(args, out_dir, specs, settings):
    tag, check = args.tag, oracle.tag_spec(args.tag)["check"]
    scores = {s["name"]: oracle.load_group(out_dir, tag, s) for s in specs}
    if check == "D":
        res = oracle.analyze_replace(specs, scores)
        print("\n" + oracle.report_replace(res))
    elif args.phase == 1:
        res = oracle.analyze_phase1(scores, settings)
        print("\n" + oracle.report_phase1(scores, specs, res))
        if args.write_chosen:
            path = oracle.ROOT / oracle.CHOSEN_FILE
            if path.exists():
                sys.exit(f"{path} already exists; it is chosen once (delete it only with a drift entry)")
            path.parent.mkdir(parents=True, exist_ok=True)
            import json
            path.write_text(json.dumps(res["chosen"], indent=1, sort_keys=True) + "\n")
            print(f"wrote {path}; commit it before phase 2")
    elif args.phase == 2:
        res = oracle.analyze_phase2(specs, scores)
        print("\n" + oracle.report_phase2(res))
    else:
        specs2 = specs_of(tag, 2, settings, args.seeds)
        scores2 = {s["name"]: oracle.load_group(out_dir, tag, s) for s in specs2}
        res = oracle.analyze_phase3(specs, scores, scores2, tag)
        print("\n" + oracle.report_phase3(res))
        scores = {**scores2, **scores}                     # the references of phase 3 are phase 2 groups
    write_csv(specs, scores, f"results/processed/oracle_{tag}_p{args.phase}.csv")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag", required=True, help="mb1 (check B) or md1 (check D)")
    ap.add_argument("--phase", type=int, default=1, help="check B only: 1 screen, 2 test, 3 lr (check D has one phase)")
    ap.add_argument("--settings", nargs="+", choices=oracle.SETTINGS, default=list(oracle.SETTINGS))
    ap.add_argument("--seeds", nargs="+", type=int, default=None, help="default: the seeds of the tag and phase")
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--threads", type=int, default=1, help="torch threads per worker (1 matches the Stage 3 runs, E-011)")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--out-dir", default=None, help="default results/raw/oracle/<tag>")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--limit", type=int, default=None, help="run at most this many of the remaining jobs")
    ap.add_argument("--analyze-only", action="store_true")
    ap.add_argument("--write-configs", action="store_true")
    ap.add_argument("--write-chosen", action="store_true", help="phase 1 analysis: write configs/oracle/mb1_chosen_rho.json")
    ap.add_argument("--smoke", action="store_true", help="pipeline test: needs --out-dir other than the default, --max-steps, --seeds")
    ap.add_argument("--max-steps", type=int, default=None, help="only with --smoke")
    args = ap.parse_args()

    if args.tag not in oracle.TAGS and not args.tag.startswith("smoke"):
        sys.exit(f"unknown tag {args.tag!r}: register it in exploratory/oracle.py TAGS and in docs/notes first; "
                 f"known tags: {', '.join(oracle.TAGS)}")
    if oracle.tag_spec(args.tag)["check"] == "D":
        args.phase = 1
    if args.phase not in oracle.tag_spec(args.tag)["seeds"]:
        sys.exit(f"phase {args.phase} does not exist for tag {args.tag}")
    default_out = pathlib.Path("results/raw/oracle") / args.tag
    out_dir = pathlib.Path(args.out_dir) if args.out_dir else default_out
    if args.smoke:
        if out_dir.resolve() == default_out.resolve() or args.max_steps is None or args.seeds is None:
            sys.exit("--smoke needs --max-steps, --seeds and an --out-dir other than results/raw/oracle/<tag>")
    elif args.max_steps is not None or args.seeds is not None:
        sys.exit("--max-steps and --seeds are only for --smoke")

    specs = specs_of(args.tag, args.phase, args.settings, args.seeds)
    ensure_configs(args.tag, specs, write=args.write_configs)
    if args.write_configs and not (args.dry_run or args.analyze_only):
        print("configs written; commit them before the runs (git add configs/oracle && git commit)")
        return

    if not args.analyze_only:
        jobs = make_jobs(args.tag, specs, out_dir)
        spec_of = {s["name"]: s for s in specs}
        cfgs = {s["name"]: oracle.build_config(s, args.tag) for s in specs}
        todo = [j for j in jobs if not existing_run(out_dir, cfgs[j.group]["stage"], cfgs[j.group]["arm"], j.seed)]
        print(f"tag {args.tag} phase {args.phase}: {len(specs)} groups, {len(jobs)} runs; {len(jobs) - len(todo)} already done, "
              f"{len(todo)} to run (out dir {out_dir})")
        if args.dry_run:
            for j in todo[:8]:
                print(f"  {j.group} seed {j.seed}  arm {cfgs[j.group]['arm']}  {j.cfg_path}")
            return
        if args.limit is not None:
            todo = todo[:args.limit]
        failed, t0 = [], time.time()

        def report(i, job, status):
            print(f"[{i}/{len(todo)}] {status:7s} {job.group}_s{job.seed}  (elapsed {time.time() - t0:7.0f}s)", flush=True)

        if args.workers <= 1:
            _init_worker(args.threads)
            for i, job in enumerate(todo, 1):
                try:
                    status = run_final_job(job, args.device, max_steps=args.max_steps)
                except Exception as e:
                    failed.append((job, repr(e)))
                    status = "FAILED"
                    print(f"   {job.group}_s{job.seed}: {e!r}", file=sys.stderr)
                report(i, job, status)
        else:
            with ProcessPoolExecutor(args.workers, mp_context=mp.get_context("spawn"), initializer=_init_worker,
                                     initargs=(args.threads,)) as ex:
                futs = {ex.submit(run_final_job, j, args.device, None, args.max_steps): j for j in todo}
                for i, fut in enumerate(as_completed(futs), 1):
                    job = futs[fut]
                    try:
                        status = fut.result()
                    except Exception as e:
                        failed.append((job, repr(e)))
                        status = "FAILED"
                        print(f"   {job.group}_s{job.seed}: {e!r}", file=sys.stderr)
                    report(i, job, status)
        if failed:
            print(f"\n{len(failed)} run(s) failed; rerun the same command to retry them:")
            for job, err in failed:
                print(f"  {job.group}_s{job.seed}: {err}")
            sys.exit(1)
        if args.limit is not None or args.smoke:
            print("\n(partial or smoke run: no analysis)")
            return

    analyze(args, out_dir, specs, args.settings)


if __name__ == "__main__":
    main()
