"""Probe of a dataset (D-031, src/datasets.py): arm A as tuned on MNIST (configs/tuned/t1_base_two.yaml, unchanged except `dataset`) is run for
3,000 steps on a few probe seeds; the plateau (median over seeds of the mean validation accuracy of the last 5 evaluations) fixes the dataset's
two accuracy targets by the rule in src/datasets.py. Run it ONCE per dataset, before any other arm is run on it, and commit the result.

  python scripts/probe_dataset.py --dataset fmnist             # three seeds (3000 to 3002), one process each when --workers 3
  python scripts/probe_dataset.py --dataset fmnist --dry-run   # what would run

Writes configs/datasets/probe_<dataset>_A.yaml (the probe config), raw logs to results/raw/probe/<dataset>/ (never overwritten) and
configs/datasets/<dataset>_targets.json (refuses to overwrite: the targets are fixed once).
"""
import argparse
import json
import multiprocessing as mp
import pathlib
import sys
from concurrent.futures import ProcessPoolExecutor

import numpy as np
import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))  # run from anywhere

from src.datasets import DATASETS, REPO, check_dataset, targets_from_plateau, targets_path
from src.final import FinalJob, existing_run, run_final_job

A_CONFIG = "configs/tuned/t1_base_two.yaml"
PROBE_SEEDS = (3000, 3001, 3002)
LATE_K = 5


def probe_config(dataset):
    cfg = yaml.safe_load(open(REPO / A_CONFIG))
    cfg.update(dataset=dataset, stage=f"probe-{dataset}", seed=0)
    return cfg


def _init_worker(threads):
    import torch
    torch.set_num_threads(threads)


def plateau_of(out_dir, cfg, seeds):
    """Median over seeds of the mean validation accuracy of the last LATE_K evaluations."""
    vals = []
    for s in seeds:
        p = existing_run(out_dir, cfg["stage"], cfg["arm"], s)
        if p is None:
            raise ValueError(f"missing probe run for seed {s} in {out_dir}")
        rows = [json.loads(l) for l in open(p) if l.strip()][1:]
        vals.append(float(np.mean([r["val_acc"] for r in rows[-LATE_K:]])))
    return float(np.median(vals)), vals


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True, choices=sorted(DATASETS))
    ap.add_argument("--seeds", nargs="+", type=int, default=list(PROBE_SEEDS))
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--threads", type=int, default=1)
    ap.add_argument("--device", default="auto")
    ap.add_argument("--out-dir", default=None, help="default results/raw/probe/<dataset>")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--max-steps", type=int, default=None, help="plumbing tests only (the targets are then not written)")
    args = ap.parse_args()
    ds = check_dataset(args.dataset)
    if ds == "mnist":
        sys.exit("MNIST keeps its targets 0.97 and 0.975 (D-003); the probe is for other datasets")
    out_dir = pathlib.Path(args.out_dir) if args.out_dir else REPO / "results" / "raw" / "probe" / ds
    tpath = targets_path(ds)
    if tpath.exists() and args.max_steps is None:
        sys.exit(f"{tpath} exists: the targets are fixed once (to change them, write a decision and a drift entry first)")
    cfg = probe_config(ds)
    cpath = REPO / "configs" / "datasets" / f"probe_{ds}_A.yaml"
    cpath.parent.mkdir(parents=True, exist_ok=True)
    if cpath.exists() and yaml.safe_load(open(cpath)) != cfg:
        sys.exit(f"{cpath} differs from its derivation (hand edit?)")
    if not cpath.exists():
        cpath.write_text(f"# Probe of dataset {ds} (D-031): arm A as tuned on MNIST, only `dataset` and `stage` changed. Generated by scripts/probe_dataset.py; do not edit.\n"
                         + yaml.safe_dump(cfg, sort_keys=False))
    jobs = [FinalJob("probeA", s, str(cpath), str(out_dir)) for s in args.seeds]
    todo = [j for j in jobs if not existing_run(out_dir, cfg["stage"], cfg["arm"], j.seed)]
    print(f"probe {ds}: {len(jobs)} runs, {len(todo)} to run (out dir {out_dir})")
    if args.dry_run:
        return
    if args.workers <= 1:
        _init_worker(args.threads)
        for j in todo:
            print(run_final_job(j, args.device, max_steps=args.max_steps), j.seed, flush=True)
    else:
        with ProcessPoolExecutor(args.workers, mp_context=mp.get_context("spawn"), initializer=_init_worker, initargs=(args.threads,)) as ex:
            for j, status in zip(todo, ex.map(run_final_job, todo, [args.device] * len(todo), [None] * len(todo), [args.max_steps] * len(todo))):
                print(status, j.seed, flush=True)
    plateau, vals = plateau_of(out_dir, cfg, args.seeds)
    lo, hi = targets_from_plateau(plateau)
    print(f"plateau of arm A on {ds}: median {plateau:.4f} over seeds {args.seeds} ({', '.join(f'{v:.4f}' for v in vals)})")
    print(f"targets by the rule of src/datasets.py: low {lo}, high {hi}")
    if args.max_steps is not None:
        print("(plumbing run: targets not written)")
        return
    tpath.write_text(json.dumps(dict(dataset=ds, targets=[lo, hi], plateau=plateau, seeds=args.seeds, per_seed=vals, rule="src/datasets.py"), indent=1) + "\n")
    print(f"wrote {tpath}; commit configs/datasets/ before any other run on {ds}")


if __name__ == "__main__":
    main()
