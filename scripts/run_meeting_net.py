"""Study 1b, the meeting network (docs/notes/meeting-network.md, D-030, DR-023). Exploratory (D-015). Nothing here is a method claim.

Registered tag: mn1 (exploratory/meetnet.py TAGS): the groups A, S, D, M1m, M1f, M1n, M1h, M1t, M2m, M2f, M3m, M3f on seeds 1500-1509,
each at the tuned config of the tuning tag t16.

Order (full commands in the note):
  python scripts/run_sweep.py --tag t16 --arms mn_match mn_fwd mn_noise mn_mh mn_table shallow mn_match_k2 mn_fwd_k2 mn_match_k3 mn_fwd_k3 --seeds 16000 16001 --workers 4
  python scripts/analyze.py select --tag t16 --write-configs         (writes configs/tuned/t16_<arm>_two.yaml; commit them)
  python scripts/run_meeting_net.py --tag mn1 --write-configs        (writes configs/mnet/mn1_<group>.yaml; commit them)
  python scripts/run_meeting_net.py --tag mn1 --workers 4            (runs and analyzes)
  python scripts/run_meeting_net.py --tag mn1 --analyze-only

Options: --dry-run, --limit N, --analyze-only, --write-configs, --workers, --threads, --device, --out-dir (default results/raw/mnet/<tag>).
Finished runs are skipped, never overwritten. --smoke needs --max-steps, --seeds and an --out-dir other than the default.
"""
import argparse
import csv
import multiprocessing as mp
import pathlib
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed

import numpy as np
import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))  # run from anywhere

from exploratory import meetnet as mn
from src.final import FinalJob, existing_run, run_final_job


def _init_worker(threads):
    import torch
    torch.set_num_threads(threads)


def ensure_configs(tag, specs, write=False):
    """The config files must equal the derivation in exploratory/meetnet.py (no hand edits)."""
    for s in specs:
        path, want = mn.config_path(tag, s["name"]), mn.build_config(s, tag)
        if not path.exists():
            if not write:
                sys.exit(f"{path} is missing; run with --write-configs, commit it, and then run")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(f"# Study 1b, tag {tag}, group {s['name']}. Generated by scripts/run_meeting_net.py from {mn.tuned_path(tag, s['name'])}; do not edit.\n"
                            + yaml.safe_dump(want, sort_keys=False))
        elif yaml.safe_load(open(path)) != want:
            sys.exit(f"{path} differs from its derivation in exploratory/meetnet.py (hand edit, or the tuned config changed since it was written?)")


def make_jobs(tag, specs, out_dir):
    """Seed-major order, so a stopped run leaves every group with the same seeds done."""
    by_seed = sorted({(seed, i) for i, s in enumerate(specs) for seed in s["seeds"]})
    return [FinalJob(specs[i]["name"], seed, str(mn.config_path(tag, specs[i]["name"])), str(out_dir)) for seed, i in by_seed]


def write_csv(scores, res, path):
    rows = []
    for name, g in scores.items():
        r = dict(group=name, n=len(g["seeds"]), mean_final_acc=float(np.mean(g["final"])))
        for t in mn.TARGETS:
            r[f"n_reached_{t}"] = int(sum(g["reached"][t]))
            r[f"mean_flops_{t}"] = float(np.mean(g["flops"][t]))
            r[f"mean_steps_{t}"] = float(np.mean(g["steps"][t]))
        for ro, v in g["readouts"].items():
            r[f"final_acc_{ro}"] = float(np.mean(v))
        if name in res["groups"]:
            q = res["groups"][name]
            r["verdict"] = q["verdict"]
            for ref, ch in (("A", q["vs_a"]), ("S", q["vs_s"])):
                for t in mn.TARGETS:
                    r[f"flops_change_vs_{ref}_{t}"], r[f"lo_vs_{ref}_{t}"], r[f"hi_vs_{ref}_{t}"] = ch[t]
        rows.append(r)
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {path}")


def analyze(tag, out_dir, specs):
    scores = {s["name"]: mn.load_group(out_dir, tag, s) for s in specs}
    res = mn.analyze(scores)
    print("\n" + mn.report(scores, res))
    write_csv(scores, res, f"results/processed/mnet_{tag}.csv")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag", required=True, help="mn1")
    ap.add_argument("--seeds", nargs="+", type=int, default=None, help="only with --smoke")
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--threads", type=int, default=1)
    ap.add_argument("--device", default="auto")
    ap.add_argument("--out-dir", default=None, help="default results/raw/mnet/<tag>")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--analyze-only", action="store_true")
    ap.add_argument("--write-configs", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--max-steps", type=int, default=None, help="only with --smoke")
    args = ap.parse_args()

    if args.tag not in mn.TAGS and not args.tag.startswith("smoke"):
        sys.exit(f"unknown tag {args.tag!r}: register it in exploratory/meetnet.py TAGS and in docs/notes first")
    tag = args.tag if args.tag in mn.TAGS else "mn1"
    default_out = pathlib.Path("results/raw/mnet") / args.tag
    out_dir = pathlib.Path(args.out_dir) if args.out_dir else default_out
    if args.smoke:
        if out_dir.resolve() == default_out.resolve() or args.max_steps is None or args.seeds is None:
            sys.exit("--smoke needs --max-steps, --seeds and an --out-dir other than results/raw/mnet/<tag>")
    elif args.max_steps is not None or args.seeds is not None:
        sys.exit("--max-steps and --seeds are only for --smoke")

    specs = mn.group_specs(tag, args.seeds)
    ensure_configs(tag, specs, write=args.write_configs)
    if args.write_configs and not (args.dry_run or args.analyze_only):
        print("configs written; commit them before the runs (git add configs/mnet && git commit)")
        return

    if not args.analyze_only:
        jobs = make_jobs(tag, specs, out_dir)
        cfgs = {s["name"]: mn.build_config(s, tag) for s in specs}
        todo = [j for j in jobs if not existing_run(out_dir, cfgs[j.group]["stage"], cfgs[j.group]["arm"], j.seed)]
        print(f"tag {tag}: {len(specs)} groups, {len(jobs)} runs; {len(jobs) - len(todo)} already done, {len(todo)} to run (out dir {out_dir})")
        if args.dry_run:
            for j in todo[:8]:
                print(f"  {j.group} seed {j.seed}  arm {cfgs[j.group]['arm']}  {j.cfg_path}")
            return
        if args.limit is not None:
            todo = todo[:args.limit]
        failed, t0 = [], time.time()

        def report(i, job, status):
            print(f"[{i}/{len(todo)}] {status:7s} {job.group}_s{job.seed}  (elapsed {time.time() - t0:7.0f}s)", flush=True)

        if args.workers <= 1:
            _init_worker(args.threads)
            for i, job in enumerate(todo, 1):
                try:
                    status = run_final_job(job, args.device, max_steps=args.max_steps)
                except Exception as e:
                    failed.append((job, repr(e)))
                    status = "FAILED"
                    print(f"   {job.group}_s{job.seed}: {e!r}", file=sys.stderr)
                report(i, job, status)
        else:
            with ProcessPoolExecutor(args.workers, mp_context=mp.get_context("spawn"), initializer=_init_worker, initargs=(args.threads,)) as ex:
                futs = {ex.submit(run_final_job, j, args.device, None, args.max_steps): j for j in todo}
                for i, fut in enumerate(as_completed(futs), 1):
                    job = futs[fut]
                    try:
                        status = fut.result()
                    except Exception as e:
                        failed.append((job, repr(e)))
                        status = "FAILED"
                        print(f"   {job.group}_s{job.seed}: {e!r}", file=sys.stderr)
                    report(i, job, status)
        if failed:
            print(f"\n{len(failed)} run(s) failed; rerun the same command to retry them:")
            for job, err in failed:
                print(f"  {job.group}_s{job.seed}: {err}")
            sys.exit(1)
        if args.limit is not None or args.smoke:
            print("\n(partial or smoke run: no analysis)")
            return

    analyze(tag, out_dir, specs)


if __name__ == "__main__":
    main()
