"""Checks G0, G1, G2: dose-response of the learned meeting loss (docs/notes/mechanism-dose-response.md, D-020;
docs/notes/mechanism-dose-follow-up.md). Exploratory (D-015). Registered tags (exploratory/dose.py TAGS):
mr1 = G0 (relu, rho 0 to 3, seeds 1100 to 1109), mr2 = G1 (relu, low doses, seeds 1110 to 1119),
mr3 = G2 (tanh, the G0 doses, seeds 1120 to 1129). Below: G0.

Arm A's tuned configuration with the arm `meet_rho` (learned G as in arm D, strength set as rho times the task
gradient at h), rho in {0, 0.1, 0.3, 1, 3}, seeds 1100 to 1109, 3,000 steps: 50 runs. Nothing is tuned. The decision
rule was written before any run (exploratory/dose.py, the note).

  python scripts/run_dose_response.py --tag mr1 --dry-run          # what would run
  python scripts/run_dose_response.py --tag mr1 --workers 4        # all 50 runs, resumable, then the analysis
  python scripts/run_dose_response.py --tag mr1 --analyze-only     # recompute the verdict from the logs
  python scripts/run_dose_response.py --tag mr1 --write-configs    # (re)write configs/dose/*.yaml if missing

Torch threads: one per worker by default, as the Stage 3 runs (E-011). Raw logs go to results/raw/dose/<tag>/ (finished
runs are skipped, never overwritten); the table goes to results/processed/dose_response_<tag>.csv.
"""
import argparse
import csv
import multiprocessing as mp
import pathlib
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))  # run from anywhere

from exploratory import dose
from src.final import FinalJob, existing_run, run_final_job


def _init_worker(threads):
    import torch
    torch.set_num_threads(threads)


def ensure_configs(tag, rhos, write=False):
    """The config files must equal the derivation in exploratory/dose.py (no hand edits). Missing files are written
    only with write=True."""
    for rho in rhos:
        path, want = dose.config_path(tag, rho), dose.build_config(rho, tag)
        if not path.exists():
            if not write:
                sys.exit(f"{path} is missing; run with --write-configs, commit it, and then run")
            path.parent.mkdir(parents=True, exist_ok=True)
            header = (f"# Check {dose.tag_spec(tag)['check']}, tag {tag}: arm A's tuned config (t1_base_two) with arm meet_rho, rho = {rho:g}, act = {want['act']}, "
                      f"lam_inv from arm D's tuned config. Generated by scripts/run_dose_response.py; do not edit.\n")
            path.write_text(header + yaml.safe_dump(want, sort_keys=False))
        elif yaml.safe_load(open(path)) != want:
            sys.exit(f"{path} differs from its derivation in exploratory/dose.py (hand edit?)")


def make_jobs(tag, seeds, rhos, out_dir):
    """Seed-major order, so a stopped run leaves every dose with the same seeds done."""
    return [FinalJob(f"rho{dose.rho_tag(rho)}", s, str(dose.config_path(tag, rho)), str(out_dir))
            for s in sorted(seeds) for rho in rhos]


def write_csv(res, path):
    rows = []
    for rho in res["rhos"]:
        for t in dose.TARGETS:
            r = dict(rho=rho, target=t, mean_steps=res["mean_steps"][rho][t], mean_flops=res["mean_flops"][rho][t],
                     n_never=res["n_never"][rho][t], **{f"diag_{k}": v for k, v in res["diag"][rho].items()})
            if rho > 0:
                for name, key in (("steps", "table"), ("flops", "flops")):
                    p, lo, hi = res[key][rho][t]
                    r.update({f"{name}_change_pct": p, f"{name}_lo": lo, f"{name}_hi": hi})
            rows.append(r)
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag", required=True, help="e.g. mr1 (names the configs, the stages and the output directory)")
    ap.add_argument("--rhos", nargs="+", type=float, default=None, help="default: the doses of the tag")
    ap.add_argument("--seeds", nargs="+", type=int, default=None, help="default: the seeds of the tag")
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--threads", type=int, default=1, help="torch threads per worker (1 matches the Stage 3 runs, E-011)")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--out-dir", default=None, help="default results/raw/dose/<tag>")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--limit", type=int, default=None, help="run at most this many of the remaining jobs")
    ap.add_argument("--analyze-only", action="store_true")
    ap.add_argument("--write-configs", action="store_true")
    ap.add_argument("--smoke", action="store_true", help="pipeline test: needs --out-dir other than the default and --max-steps")
    ap.add_argument("--max-steps", type=int, default=None, help="only with --smoke")
    args = ap.parse_args()

    if args.tag not in dose.TAGS and not args.tag.startswith("smoke"):
        sys.exit(f"unknown tag {args.tag!r}: register it in exploratory/dose.py TAGS (with its doses, seeds and rule) "
                 f"and in docs/notes first; known tags: {', '.join(dose.TAGS)}")
    spec = dose.tag_spec(args.tag)
    args.rhos = list(spec["rhos"]) if args.rhos is None else args.rhos
    args.seeds = list(spec["seeds"]) if args.seeds is None else args.seeds
    default_out = pathlib.Path("results/raw/dose") / args.tag
    out_dir = pathlib.Path(args.out_dir) if args.out_dir else default_out
    if args.smoke:
        if out_dir.resolve() == default_out.resolve() or args.max_steps is None:
            sys.exit("--smoke needs --max-steps and an --out-dir other than results/raw/dose/<tag>")
    elif args.max_steps is not None:
        sys.exit("--max-steps is only for --smoke")
    if 0.0 not in args.rhos:
        sys.exit("rho = 0 is the reference and must be among the doses")
    ensure_configs(args.tag, args.rhos, write=args.write_configs)
    if args.write_configs and not (args.dry_run or args.analyze_only):
        print("configs written; commit them before the runs (git add configs/dose && git commit)")
        return

    if not args.analyze_only:
        jobs = make_jobs(args.tag, args.seeds, args.rhos, out_dir)
        todo = [j for j in jobs if not existing_run(out_dir, dose.stage_name(args.tag, float(j.group[3:].replace("p", "."))), "meet_rho", j.seed)]
        print(f"tag {args.tag}: {len(args.rhos)} doses x {len(args.seeds)} seeds = {len(jobs)} runs; "
              f"{len(jobs) - len(todo)} already done, {len(todo)} to run (out dir {out_dir})")
        if args.dry_run:
            for j in todo[:5]:
                print(f"  {j.group} seed {j.seed}  {j.cfg_path}")
            return
        if args.limit is not None:
            todo = todo[:args.limit]
        failed, t0 = [], time.time()

        def report(i, job, status):
            print(f"[{i}/{len(todo)}] {status:7s} {job.group}_s{job.seed}  (elapsed {time.time() - t0:7.0f}s)", flush=True)

        if args.workers <= 1:
            _init_worker(args.threads)
            for i, job in enumerate(todo, 1):
                try:
                    status = run_final_job(job, args.device, max_steps=args.max_steps)
                except Exception as e:
                    failed.append((job, repr(e)))
                    status = "FAILED"
                    print(f"   {job.group}_s{job.seed}: {e!r}", file=sys.stderr)
                report(i, job, status)
        else:
            with ProcessPoolExecutor(args.workers, mp_context=mp.get_context("spawn"), initializer=_init_worker,
                                     initargs=(args.threads,)) as ex:
                futs = {ex.submit(run_final_job, j, args.device, None, args.max_steps): j for j in todo}
                for i, fut in enumerate(as_completed(futs), 1):
                    job = futs[fut]
                    try:
                        status = fut.result()
                    except Exception as e:
                        failed.append((job, repr(e)))
                        status = "FAILED"
                        print(f"   {job.group}_s{job.seed}: {e!r}", file=sys.stderr)
                    report(i, job, status)
        if failed:
            print(f"\n{len(failed)} run(s) failed; rerun the same command to retry them:")
            for job, err in failed:
                print(f"  {job.group}_s{job.seed}: {err}")
            sys.exit(1)
        if args.limit is not None or args.smoke:
            print("\n(partial or smoke run: no analysis)")
            return

    res = dose.analyze(out_dir, args.tag, args.seeds, args.rhos)
    print("\n" + dose.format_report(res, args.tag))
    write_csv(res, f"results/processed/dose_response_{args.tag}.csv")


if __name__ == "__main__":
    main()
